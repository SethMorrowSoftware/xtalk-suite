#!/usr/bin/env python3
"""check-web-names.py - src/xlsx_web_names.h, and the web archive's names.

The web build is a static archive linked INTO OXT-Beyond's web engine, and
that engine has libraries of its own: a zlib certainly, and whatever else a
later release adds. xlsxt carries a zlib, its minizip, an Expat, an MD5 and
libxlsxwriter, and two definitions of `inflate` or `MD5_Init` cannot both
link (or worse, can, and one side calls the other's). So for the web build
every global name of those libraries is renamed to xlxw_<name> by one header,
src/xlsx_web_names.h, that CMakeLists.txt puts first into every translation
unit (`-include`). The shim's own exports stay xlx_*, which the binding
names.

    python3 tools/check-web-names.py
        the gate, compiler-free: the header is what this tool would write
        from its own list (one `#define NAME xlxw_NAME` per line, sorted, no
        name twice, none of the shim's), and CMakeLists.txt includes it.

    python3 tools/check-web-names.py --archive build-web/xlsxt.a [--nm llvm-nm]
        the web lane's check, after the build: every global the archive
        DEFINES is xlx_*, xlxw_* or the export table. A name that is none of
        those is a library name the header missed (a pin was bumped, or the
        wasm build compiles a function the native one does not).

    python3 tools/check-web-names.py --write --from build/libxlsxt_deps.a [--nm nm]
        rewrite the header from a NATIVE build's static library of the three
        libraries (cmake builds it as libxlsxt_deps.a / xlsxt_deps.lib), plus
        EXTRA below. Names are added, never dropped by hand.

Exit status: 0 held, 1 a difference, 2 an input could not be read.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "src", "xlsx_web_names.h")
CMAKE = os.path.join(ROOT, "CMakeLists.txt")

PREFIX = "xlxw_"
# Globals the archive may define under their own names: the shim's exports
# (the binding binds them by name) and the table the engine asks for.
OWN = re.compile(r"^(xlx_\w+|xlsxt_web_exports)$")
# Global names that are not in the three libraries' static library: the one
# function the SHIM defines for libxlsxwriter (CMakeLists.txt says why).
EXTRA = ["emyg_dtoa"]
# A header with fewer names than this was written from the wrong library.
MIN_NAMES = 500

BEGIN = "/* >>> BEGIN NAMES (generated: tools/check-web-names.py --write) >>> */"
END = "/* <<< END NAMES <<< */"
DEFINE = re.compile(r"^#define (\w+) (\w+)$")

PROLOGUE = """/*
 * xlsx_web_names.h - GENERATED by tools/check-web-names.py --write; the list
 * between the markers is never edited by hand.
 *
 * For the web build only (CMakeLists.txt puts it first into every
 * translation unit there). xlsxt's web archive is linked INTO an engine that
 * has a zlib of its own, so every global name of the libraries inside xlsxt
 * (zlib and its minizip, Expat, libxlsxwriter and the two small libraries it
 * carries) is renamed here to xlxw_<name>. The preprocessor does it, so the
 * sources are untouched; zlib's own Z_PREFIX has already turned `inflate`
 * into `z_inflate`, and this turns that into `xlxw_z_inflate`. The shim's
 * exports, xlx_*, keep their names: the binding binds them.
 *
 * The desktop libraries do not need this: they hide every name but xlx_*
 * (src/xlsxt.map). A static archive has no such switch.
 */
#ifndef XLSX_WEB_NAMES_H
#define XLSX_WEB_NAMES_H

"""
EPILOGUE = "\n#endif\n"


def render(names):
    return (PROLOGUE + BEGIN + "\n" + "".join("#define %s %s%s\n" % (n, PREFIX, n) for n in sorted(set(names)))
            + END + "\n" + EPILOGUE)


def header_names(text):
    """(names, problems) of a header's text."""
    problems = []
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        return [], ["xlsx_web_names.h: the NAMES marker pair is missing or repeated"]
    body = text[text.index(BEGIN) + len(BEGIN):text.index(END)]
    names = []
    for line in body.split("\n"):
        if not line:
            continue
        m = DEFINE.match(line)
        if not m:
            problems.append("xlsx_web_names.h: a line that is not `#define NAME %sNAME`: %r" % (PREFIX, line))
            continue
        if m.group(2) != PREFIX + m.group(1):
            problems.append("xlsx_web_names.h: %s is renamed to %s, not %s%s"
                            % (m.group(1), m.group(2), PREFIX, m.group(1)))
        if OWN.match(m.group(1)) or m.group(1).startswith(PREFIX):
            problems.append("xlsx_web_names.h: %s must keep its name (the binding binds xlx_*)" % m.group(1))
        names.append(m.group(1))
    return names, problems


def check_header(text, cmake_text):
    """Problems. Pure: the fixture test drives it on mutated text."""
    names, problems = header_names(text)
    seen = set()
    for n in names:
        if n in seen:
            problems.append("xlsx_web_names.h: %s is renamed twice" % n)
        seen.add(n)
    if len(names) < MIN_NAMES:
        problems.append("xlsx_web_names.h: only %d names (floor %d): written from the wrong library?"
                        % (len(names), MIN_NAMES))
    for n in EXTRA:
        if n not in seen:
            problems.append("xlsx_web_names.h: %s (defined by the shim for libxlsxwriter) is not renamed" % n)
    if not problems and text != render(names):
        problems.append("xlsx_web_names.h is not what --write would write (sorted, one name per line, "
                        "the prologue unchanged)")
    if 'src/xlsx_web_names.h"' not in cmake_text or "-include" not in cmake_text:
        problems.append("CMakeLists.txt no longer puts src/xlsx_web_names.h into the web build (-include)")
    return problems


def defined_globals(nm_text):
    """The global names an `nm -g --defined-only` listing defines."""
    out = set()
    for line in nm_text.split("\n"):
        parts = line.split()
        # "address TYPE name" (ELF, wasm); an undefined "U name" has two parts
        if len(parts) == 3 and len(parts[1]) == 1 and parts[1] not in "Uu":
            out.add(parts[2])
    return out


def check_archive(nm_text, header_text):
    """Problems of a WEB archive's nm listing."""
    defined = defined_globals(nm_text)
    problems = []
    if not any(n.startswith("xlx_") for n in defined):
        return ["the archive defines no xlx_* name: is this the web archive, and could nm read it?"]
    for n in sorted(defined):
        if OWN.match(n) or n.startswith(PREFIX):
            continue
        problems.append("the archive defines the global %s under its own name: the engine it is linked "
                        "into may define it too (rebuild src/xlsx_web_names.h with --write, or name it "
                        "in EXTRA)" % n)
    if "xlsxt_web_exports" not in defined:
        problems.append("the archive does not define xlsxt_web_exports")
    return problems


def unused_names(nm_text, header_text):
    """Renamed names this archive does not define. Not a failure: the native
    library the header was written from compiles a few functions the wasm one
    does not. main() prints the count, so a pin bump that drops hundreds is
    seen."""
    names, _ = header_names(header_text)
    defined = defined_globals(nm_text)
    return [n for n in names if PREFIX + n not in defined]


def run_nm(nm, path):
    try:
        return subprocess.run([nm, "-g", "--defined-only", path], check=True, capture_output=True,
                              text=True).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        print("check-web-names: cannot run %s on %s: %s" % (nm, path, e))
        return None


def main(argv):
    def value(flag, default=None):
        return argv[argv.index(flag) + 1] if flag in argv and argv.index(flag) + 1 < len(argv) else default

    if "--write" in argv:
        source = value("--from")
        if not source:
            print("check-web-names: --write needs --from <the native static library of the three libraries>")
            return 2
        listing = run_nm(value("--nm", "nm"), source)
        if listing is None:
            return 2
        names = sorted((defined_globals(listing) | set(EXTRA)) - {n for n in defined_globals(listing) if OWN.match(n)})
        # macOS and 32-bit Windows spell a C name with a leading underscore;
        # the header must be written from an ELF build, where they do not.
        if len(names) < MIN_NAMES:
            print("check-web-names: only %d names in %s (floor %d)" % (len(names), source, MIN_NAMES))
            return 2
        with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(names))
        print("check-web-names: wrote src/xlsx_web_names.h (%d names)" % len(names))
    try:
        text = open(HEADER, encoding="utf-8").read()
        cmake_text = open(CMAKE, encoding="utf-8").read()
    except OSError as e:
        print("check-web-names: cannot read its inputs: %s" % e)
        return 2
    problems = check_header(text, cmake_text)
    archive = value("--archive")
    if archive:
        listing = run_nm(value("--nm", "nm"), archive)
        if listing is None:
            return 2
        problems += check_archive(listing, text)
        unused = unused_names(listing, text)
        if unused:
            print("check-web-names: NOTE %d renamed name(s) are not defined by this archive" % len(unused))
    if problems:
        print("check-web-names: FAILED")
        for p in problems[:40]:
            print("  - " + p)
        if len(problems) > 40:
            print("  ... and %d more" % (len(problems) - 40))
        return 1
    names, _ = header_names(text)
    print("check-web-names: OK (%d library names renamed to %s*%s)"
          % (len(names), PREFIX, "; the archive defines no other global but xlx_* and the table" if archive else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
