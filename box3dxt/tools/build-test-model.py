#!/usr/bin/env python3
"""build-test-model.py - tests/models/teapot.obj as a C header.

The smoke test runs where there is no file to open (a wasm module under node,
a bare binary pushed to an Android emulator), so the model the tests load is
carried as arrays in tests/teapot_model.h, GENERATED from the .obj here.
The .obj stays the source: tests/engine-selftest.lc parses that file itself,
the way a stack would.

    python3 tools/build-test-model.py           rewrite the header
    python3 tools/build-test-model.py --check   fail if it is stale (a gate)

Only `v x y z` and triangular `f a b c` lines are read (a/b/c index forms are
cut at the slash); anything else in the file is refused, so a model that
needs more than this reader has is noticed here and not in a test.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OBJ = os.path.join(ROOT, "tests", "models", "teapot.obj")
OUT = os.path.join(ROOT, "tests", "teapot_model.h")
TAG = "build-test-model"


def read_obj(path):
    points, triangles = [], []
    with open(path, "rb") as handle:
        raw = handle.read()
    for number, line in enumerate(raw.decode("ascii").splitlines(), 1):
        parts = line.split()
        if not parts or parts[0].startswith("#"):
            continue
        if parts[0] == "v" and len(parts) == 4:
            points.append(tuple(parts[1:4]))
            for text in parts[1:4]:
                float(text)
        elif parts[0] == "f" and len(parts) == 4:
            triangles.append(tuple(int(p.split("/")[0]) for p in parts[1:4]))
        else:
            raise SystemExit(f"{TAG}: {path}:{number}: a line this reader does "
                             f"not know: {line!r}")
    for tri in triangles:
        for index in tri:
            if not 1 <= index <= len(points):
                raise SystemExit(f"{TAG}: a face names point {index} of "
                                 f"{len(points)}")
    return raw, points, triangles


def render():
    raw, points, triangles = read_obj(OBJ)
    digest = hashlib.sha256(raw).hexdigest()
    out = []
    out.append("/* teapot_model.h - GENERATED by tools/build-test-model.py from")
    out.append(" * tests/models/teapot.obj; edit neither, regenerate. The gate")
    out.append(" * (--check) holds this file to that one.")
    out.append(f" * sha256 of the .obj: {digest}")
    out.append(" * Points are x, y, z; triangles name points from 1, as the .obj")
    out.append(" * does and as b3x_geometry_add_triangle wants them. */")
    out.append("#ifndef TEAPOT_MODEL_H")
    out.append("#define TEAPOT_MODEL_H")
    out.append(f"#define TEAPOT_POINT_COUNT {len(points)}")
    out.append(f"#define TEAPOT_TRIANGLE_COUNT {len(triangles)}")
    out.append("static const float kTeapotPoints[TEAPOT_POINT_COUNT][3] = {")
    for x, y, z in points:
        out.append(f"    {{{float(x)!r}f, {float(y)!r}f, {float(z)!r}f}},")
    out.append("};")
    out.append("static const short kTeapotTriangles[TEAPOT_TRIANGLE_COUNT][3] = {")
    for a, b, c in triangles:
        out.append(f"    {{{a}, {b}, {c}}},")
    out.append("};")
    out.append("#endif")
    if len(points) > 32767:
        raise SystemExit(f"{TAG}: more points than a short can name")
    return "\n".join(out) + "\n", len(points), len(triangles)


def main(argv):
    text, points, triangles = render()
    if "--check" in argv:
        try:
            with open(OUT, encoding="ascii") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current != text:
            print(f"{TAG}: tests/teapot_model.h does not match "
                  f"tests/models/teapot.obj - run python3 tools/build-test-model.py")
            return 1
        print(f"{TAG}: OK (tests/teapot_model.h matches the .obj: {points} "
              f"points, {triangles} triangles)")
        return 0
    with open(OUT, "w", encoding="ascii", newline="\n") as handle:
        handle.write(text)
    print(f"{TAG}: wrote tests/teapot_model.h ({points} points, {triangles} triangles)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
