#!/usr/bin/env python3
"""build-test-assets.py - tests/test_assets.h from the files in tests/assets/.

The two native tests read model and picture FILES (the loaders take a path),
and they run where there is no checkout beside them: on the Android emulator
a test is one pushed binary, and under node the web build sees an in-memory
file system. So the files travel INSIDE the test: this tool writes them into
one header as byte arrays, with the few lines that put them back on disk in
a scratch folder at start and take them away at the end.

tests/assets/ stays the source (the engine self-test reads the files there
by path); the header is generated, and stale is a failure:

    python3 tools/build-test-assets.py           # rewrite the header
    python3 tools/build-test-assets.py --check   # the gate: 0 fresh, 1 stale, 2 unreadable
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "tests", "assets")
HEADER = os.path.join(ROOT, "tests", "test_assets.h")

# Fewer files than this means the folder was not found or was emptied: a
# header with no files in it would compile and test nothing.
MIN_ASSETS = 6

HELPERS = r'''
/* Where the files are put back: the first of these that can be created.
 * The current folder first (a build tree, an adb shell's pushed folder,
 * node's in-memory root), then the usual temporary places. */
#if defined(_WIN32)
#include <direct.h>
#include <process.h>
#define R3T_MKDIR(p) _mkdir(p)
#define R3T_RMDIR(p) _rmdir(p)
#define R3T_PID() ((unsigned)_getpid())
#else
#include <sys/stat.h>
#include <unistd.h>
#define R3T_MKDIR(p) mkdir((p), 0700)
#define R3T_RMDIR(p) rmdir(p)
#define R3T_PID() ((unsigned)getpid())
#endif

static char s_asset_dir[512];
static char s_asset_path[4][768];
static int s_asset_turn;

/* The path of one carried file (or of a name that is NOT carried, for the
 * "missing file" cases). Four results stay valid at once. */
static const char *asset(const char *name)
{
    char *out = s_asset_path[s_asset_turn++ & 3];
    snprintf(out, sizeof s_asset_path[0], "%s/%s", s_asset_dir, name);
    return out;
}

static int assets_try(const char *base)
{
    size_t i;
    if (!base || !base[0] || strlen(base) > 400) return 0;
    /* the process id in the name: ctest may run both tests at once, in
     * one folder */
    snprintf(s_asset_dir, sizeof s_asset_dir, "%s/r3x-test-assets-%u-%u", base,
             (unsigned)time(NULL) % 100000u, R3T_PID());
    if (R3T_MKDIR(s_asset_dir) != 0) return 0;
    for (i = 0; i < sizeof k_assets / sizeof k_assets[0]; i++) {
        FILE *f = fopen(asset(k_assets[i].name), "wb");
        if (!f) return 0;
        if (fwrite(k_assets[i].data, 1, k_assets[i].len, f) != k_assets[i].len) { fclose(f); return 0; }
        if (fclose(f) != 0) return 0;
    }
    return 1;
}

/* 1 once every file is on disk; 0 if no folder could be written (the test
 * then fails by name instead of reporting loader failures it caused). */
static int assets_write(void)
{
    if (assets_try(".")) return 1;
    if (assets_try(getenv("TMPDIR"))) return 1;
    if (assets_try(getenv("TEMP"))) return 1;
    if (assets_try("/tmp")) return 1;
    if (assets_try("/data/local/tmp")) return 1;
    s_asset_dir[0] = 0;
    return 0;
}

static void assets_remove(void)
{
    size_t i;
    if (!s_asset_dir[0]) return;
    for (i = 0; i < sizeof k_assets / sizeof k_assets[0]; i++) remove(asset(k_assets[i].name));
    R3T_RMDIR(s_asset_dir);
}
'''


def build():
    names = sorted(n for n in os.listdir(ASSETS) if os.path.isfile(os.path.join(ASSETS, n)))
    if len(names) < MIN_ASSETS:
        raise OSError("only %d files in tests/assets (fewer than %d)" % (len(names), MIN_ASSETS))
    out = ["/* test_assets.h - GENERATED by tools/build-test-assets.py from tests/assets/.",
           " * Edit the files there and run the tool; its --check is a gate.",
           " * Included by tests/smoke_test.c and tests/fuzz_test.c after <stdio.h>,",
           " * <stdlib.h>, <string.h> and <time.h>. */",
           "#ifndef R3X_TEST_ASSETS_H",
           "#define R3X_TEST_ASSETS_H", ""]
    for i, name in enumerate(names):
        with open(os.path.join(ASSETS, name), "rb") as f:
            data = f.read()
        if not data:
            raise OSError("tests/assets/%s is empty" % name)
        out.append("/* %s, %d bytes */" % (name, len(data)))
        out.append("static const unsigned char k_asset_%d[] = {" % i)
        for at in range(0, len(data), 16):
            out.append("    " + ", ".join("0x%02x" % b for b in data[at:at + 16]) + ",")
        out.append("};")
    out.append("")
    out.append("static const struct { const char *name; const unsigned char *data; unsigned len; } k_assets[] = {")
    for i, name in enumerate(names):
        out.append('    { "%s", k_asset_%d, (unsigned)sizeof k_asset_%d },' % (name, i, i))
    out.append("};")
    out.append(HELPERS.rstrip("\n"))
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n", len(names)


def main():
    check = "--check" in sys.argv[1:]
    try:
        want, count = build()
    except OSError as err:
        print("build-test-assets: cannot read tests/assets: %s" % err)
        return 2
    try:
        with open(HEADER, encoding="utf-8") as f:
            have = f.read()
    except OSError:
        have = None
    if check:
        if have != want:
            print("FAIL tests/test_assets.h is not what tests/assets/ holds (run tools/build-test-assets.py)")
            return 1
        print("build-test-assets: OK (tests/test_assets.h carries the %d files of tests/assets/)" % count)
        return 0
    if have != want:
        with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
            f.write(want)
        print("build-test-assets: wrote tests/test_assets.h (%d files)" % count)
    else:
        print("build-test-assets: tests/test_assets.h is fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
