#!/usr/bin/env python3
"""sync-member-readmes.py - the "Relationship to the xTalk suite" section of
every member README, DERIVED from the registries rather than written once.

WHY THIS EXISTS. Each member is published into a repository of its own
(tools/publish-members.py; docs/MEMBER-REPO-SPLIT.md). A reader arriving at
that repository needs four things its README did not say on 2026-09-21:
where the member is developed (the suite, permanently, since the 2026-09-22
decision - so also how a contribution made there comes home) and where its
suite-level citations (`docs/OXT-ENGINE-NOTES.md`,
`tools/build-all.sh`, `../coinxt/...`) resolve; which SIBLING members its
gates need beside it and how to point them there; which CARRIED COPIES it
holds (the UI kit, the boot self-check, the harness scaffold, sibling
libraries embedded into its demos, the unified checker) and where the
masters and drift gates for those live, since none of that machinery
travels with the member; and what its own gate runner cannot check alone.

Every one of those facts already lives in a registry in tools/ - the member
table, sync-demo-embeds.py's REGISTRY, the three drift gates' adopter lists,
check-checker-drift.py's copy sets. Writing them into eleven READMEs by hand
is how the root README's coverage ratio and the ABI numbers went stale, so
this tool reads the registries and writes the section between two HTML
comment sentinels (invisible when rendered), and --check refuses a README
whose section is not what the registries derive. Edit the registries, not
the section.

    python3 tools/sync-member-readmes.py           # write
    python3 tools/sync-member-readmes.py --check   # gate (in build-all.sh)

The section is ASCII with plain hyphens, because four members run
check-docs-style.py over their own prose and this text lands in theirs.
"""

import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


REG = _load("member_registry", os.path.join(HERE, "member-registry.py"))
EMBEDS = _load("sync_demo_embeds", os.path.join(HERE, "sync-demo-embeds.py"))
UIKIT = _load("check_ui_kit_drift", os.path.join(HERE, "check-ui-kit-drift.py"))
