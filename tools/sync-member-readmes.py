    own = []
    for demo, providers in sorted(EMBEDS.REGISTRY.items()):
        if not _mine(demo, m):
            continue
        for p in providers:
            if _mine(p, m):
                own.append((_strip(demo, m), _strip(p, m)))
    if embeds:
        w("- Sibling libraries embedded by the suite's `tools/sync-demo-embeds.py`"
          " (the copy is the shipped file; the master is the sibling's `src/`):")
